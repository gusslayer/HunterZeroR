/// Return the glyph for a character, falling back to `?`.
pub fn glyph(character: char) -> Glyph {
    let upper = character.to_ascii_uppercase();
    for (candidate, rows) in GLYPHS {
        if *candidate == upper {
            return *rows;
        }
    }
    for (candidate, rows) in GLYPHS {
        if *candidate == '?' {
            return *rows;
        }
    }
    ["00000000"; 8]
}

/// Replace accented Latin characters with their ASCII equivalents.
///
/// The bitmap font only contains the characters used by the original Python
/// implementation.  This mirrors `core.ui.widgets.plain_text` without pulling in
/// a Unicode normalisation dependency.
pub fn plain_text(input: &str) -> String {
    let mut output = String::with_capacity(input.len());
    for character in input.chars() {
        let mapped = match character {
            'á' | 'à' | 'ä' | 'â' | 'ã' | 'å' => 'a',
            'Á' | 'À' | 'Ä' | 'Â' | 'Ã' | 'Å' => 'A',
            'é' | 'è' | 'ë' | 'ê' => 'e',
            'É' | 'È' | 'Ë' | 'Ê' => 'E',
            'í' | 'ì' | 'ï' | 'î' => 'i',
            'Í' | 'Ì' | 'Ï' | 'Î' => 'I',
            'ó' | 'ò' | 'ö' | 'ô' | 'õ' => 'o',
            'Ó' | 'Ò' | 'Ö' | 'Ô' | 'Õ' => 'O',
            'ú' | 'ù' | 'ü' | 'û' => 'u',
            'Ú' | 'Ù' | 'Ü' | 'Û' => 'U',
            'ñ' => 'n',
            'Ñ' => 'N',
            'ç' => 'c',
            'Ç' => 'C',
            '\u{00A0}' => ' ',
            '\t' | '\r' | '\n' => ' ',
            other if other.is_control() => continue,
            other => other,
        };
        output.push(mapped);
    }
    output
}

/// Width in pixels of a string at the requested integer scale.
pub fn text_width(text: &str, scale: i32) -> i32 {
    text.chars().count() as i32 * 8 * scale.max(1)
}

/// Height in pixels of a line at the requested integer scale.
#[allow(dead_code)]
pub fn text_height(scale: i32) -> i32 {
    8 * scale.max(1)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn text_width_is_eight_pixels_per_character() {
        assert_eq!(text_width("ABC", 1), 24);
        assert_eq!(text_width("ABC", 2), 48);
    }

    #[test]
    fn accents_are_flattened() {
        assert_eq!(plain_text("Métrica única"), "Metrica unica");
    }

    #[test]
    fn every_ascii_letter_has_a_glyph() {
        for character in ('A'..='Z').chain('0'..='9') {
            assert_eq!(glyph(character), glyph(character.to_ascii_lowercase()));
        }
    }
}
